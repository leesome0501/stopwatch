@pytest.mark.parametrize("fmt, header, row, amount, balance", CASES, ids=[c[0] for c in CASES])
def test_real_bank_headers(fmt, header, row, amount, balance):
    # 은행 파일처럼 위에 제목·계좌번호 줄이 있는 상태로 넣는다
    r = parse_file(xlsx_bytes([["거래내역 조회"], ["계좌번호", "123-456-789012"], [], header, row]))
    assert r.format == fmt
    assert len(r.rows) == 1 and r.rows[0].amount == amount and r.rows[0].balance_after == balance
    assert r.account_number in ("123-456-789012", None)


def test_header_with_parenthesis_suffix():
    """'거래일시(기업)' 처럼 괄호가 붙어도 포함 검사로 찾는다."""
    r = parse_file(xlsx_bytes([["거래일시(기업)", "출금", "입금", "거래후 잔액", "거래내용"],
                               ["2026-08-31 09:00", "1,000", "", "9,000", "커피"]]))
    assert r.format == "IBK" and r.rows[0].amount == D(-1000)
